#!/usr/bin/env bash
# ===========================================================================
# sync-windows-hosts.sh — sinkronisasi domain *.test ke hosts Windows
#
# Kenapa script ini ada: agent DNS Windows lerd (`lerd.exe --agent`) bind
# `127.0.0.1:53`, tapi di mesin ini listener lain (svchost, `0.0.0.0:53`)
# menelan setiap query DNS yang valid — socket yang ter-bind tapi
# ter-shadow tidak bisa dideteksi lerd. Akibatnya `*.test` tidak pernah
# resolve di sisi Windows.
#
# Workaround terbukti: tulis domain site terdaftar sebagai `127.0.0.1` di
# hosts Windows. Dengan WSL2 mirrored networking, `127.0.0.1:443` Windows
# menjangkau nginx di WSL, jadi entri hosts cukup.
#
# Yang dikerjakan:
#   1. Baca ~/.local/share/lerd/sites.yaml, ambil semua domain ber-TLD
#      .test / .localhost (de-duplikasi + sort)
#   2. Tulis blok bertanda `# >>> lerd` … `# <<< lerd` ke
#      C:\Windows\System32\drivers\etc\hosts via PowerShell elevated
#      (satu prompt UAC; backup, hapus ReadOnly sementara, ipconfig
#      /flushdns — semuanya di dalam script elevated)
#
# Idempoten: blok lama dihapus dulu sebelum blok baru ditulis; baris lain
# di hosts tidak disentuh sama sekali.
#
# Usage:
#   ./sync-windows-hosts.sh            # sinkronisasi (satu prompt UAC)
#   ./sync-windows-hosts.sh --check    # laporkan drift saja, tanpa menulis
#   ./sync-windows-hosts.sh --dry-run  # cetak blok yang akan ditulis
# ===========================================================================
set -euo pipefail

SITES_YAML="$HOME/.local/share/lerd/sites.yaml"
HOSTS_WIN='C:\Windows\System32\drivers\etc\hosts'
BLOCK_START='# >>> lerd (.test) >>>  generated by lerd/sync-windows-hosts.sh'
BLOCK_END='# <<< lerd (.test) <<<'
CHECK_ONLY=0
DRY_RUN=0

log()  { printf '\033[1;32m[lerd]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[lerd]\033[0m %s\n' "$*"; }
err()  { printf '\033[1;31m[lerd]\033[0m %s\n' "$*" >&2; }
usage() { sed -n 's/^# \{0,1\}//p' "${BASH_SOURCE[0]}" | sed -n '2,26p'; }

for arg in "$@"; do
  case "$arg" in
    --help|-h) usage; exit 0;;
    --check)   CHECK_ONLY=1;;
    --dry-run) DRY_RUN=1;;
    *) warn "unknown flag: $arg";;
  esac
done

# --- helpers ---------------------------------------------------------------
is_wsl() { grep -qi microsoft /proc/sys/kernel/osrelease 2>/dev/null; }
win_path() { wslpath -u "$1" 2>/dev/null; }

# --- 0. sanity -------------------------------------------------------------
is_wsl || { err "bukan WSL2 (kernel bukan Microsoft). Script ini untuk WSL."; exit 1; }

HOSTS="$(win_path "$HOSTS_WIN")"
[ -f "$HOSTS" ] || { err "hosts Windows tidak terjangkau di $HOSTS (interop/drive C mati?)"; exit 1; }

[ -f "$SITES_YAML" ] || { err "sites.yaml tidak ada: $SITES_YAML — lerd belum punya site terdaftar?"; exit 1; }

# --- 1. sumber kebenaran: domains dari sites.yaml --------------------------
# Format: daftar `domains:` per site, satu domain per baris (indentasi bebas).
# Ambil yang TLD-nya .test / .localhost, buang duplikat, sort.
DOMAINS="$(awk '
  /^[[:space:]]*domains:/ { inlist=1; next }
  inlist && /^[[:space:]]*-/ {
    d=$0; sub(/^[[:space:]]*-[[:space:]]*/, "", d); sub(/[[:space:]]+$/, "", d);
    sub(/^["'\'']/, "", d); sub(/["'\'']$/, "", d);
    if (d ~ /\.test$/ || d ~ /\.localhost$/) print d; next
  }
  { inlist=0 }
' "$SITES_YAML" | sort -u)"

COUNT="$(printf '%s\n' "$DOMAINS" | grep -c . || true)"
[ "$COUNT" -gt 0 ] || { err "tidak ada domain .test/.localhost di $SITES_YAML"; exit 1; }

log "$COUNT domain ditemukan di sites.yaml"

# --- 2. susun blok (CRLF + TAB) --------------------------------------------
BLOCK="$BLOCK_START"
while IFS= read -r d; do
  BLOCK+=$'\r\n'"127.0.0.1	$d"
done <<< "$DOMAINS"
BLOCK+=$'\r\n'"$BLOCK_END"

if [ "$DRY_RUN" -eq 1 ]; then
  printf '%s\n\n' "$BLOCK" | tr -d '\r'
  log "dry-run: blok di atas yang akan ditulis ke $HOSTS_WIN"
  exit 0
fi

# --- 3. --check: bandingkan dengan isi hosts -------------------------------
# In-sync berarti blok lerd yang ada identik dengan blok baru. Keputusan
# tidak boleh lewat pipeline (subshell menelan exit), jadi pakai for +
# flag eksplisit.
in_sync() {
  local cur ok=1 d
  cur="$(awk -v s="$BLOCK_START" -v e="$BLOCK_END" '
    index($0, s) { on=1; next } index($0, e) { on=0; next } on
  ' "$HOSTS" | tr -d '\r')"
  [ "$(printf '%s\n' "$cur" | grep -c . || true)" -eq "$COUNT" ] || return 1
  for d in $DOMAINS; do
    grep -qF "127.0.0.1	$d" <<< "$cur" || ok=0
  done
  [ "$ok" -eq 1 ]
}

if [ "$CHECK_ONLY" -eq 1 ]; then
  if in_sync; then
    log "hosts Windows sudah sinkron ($COUNT domain)"
  else
    warn "hosts Windows TIDAK sinkron ($COUNT domain di sites.yaml) — jalankan ulang tanpa --check"
    exit 1
  fi
  exit 0
fi

# --- 4. tulis via PowerShell elevated (satu prompt UAC) --------------------
# Temp .ps1 harus di filesystem Windows lokal, bukan /tmp WSL: proses
# elevated Windows membaca UNC \\wsl.localhost\… secara tidak andal.
PS_TMP_WIN="$(powershell.exe -NoProfile -Command '$env:TEMP' 2>/dev/null | tr -d '\r')"
[ -n "$PS_TMP_WIN" ] || { err "tidak bisa resolve %TEMP% Windows (interop mati?)"; exit 1; }
PS_TMP="$(win_path "$PS_TMP_WIN")"
mkdir -p "$PS_TMP"
PS1_WIN="$PS_TMP_WIN\lerd-sync-hosts.ps1"
PS1="$PS_TMP/lerd-sync-hosts.ps1"

# Body PowerShell dipakai verbatim dari implementasi yang sudah terbukti
# jalan di mesin ini (heredoc single-quoted: bash tidak mengekspansi apa
# pun). Placeholder LERD_DOMAINS diganti daftar domain sebelum ditulis.
cat <<'PS1' > "$PS1"
$ErrorActionPreference = 'Stop'
$hosts = 'C:\Windows\System32\drivers\etc\hosts'
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$bak = $hosts + '.bak-' + $stamp
Copy-Item -LiteralPath $hosts -Destination $bak -Force

$wasReadOnly = (Get-Item -LiteralPath $hosts).IsReadOnly
if ($wasReadOnly) { Set-ItemProperty -LiteralPath $hosts -Name IsReadOnly -Value $false }
if ((Get-Item -LiteralPath $bak).IsReadOnly) { Set-ItemProperty -LiteralPath $bak -Name IsReadOnly -Value $false }

$domains = @(
LERD_DOMAINS
)
$nl = [string][char]13 + [string][char]10
$tab = [string][char]9
$lines = Get-Content -LiteralPath $hosts
$acc = New-Object System.Collections.Generic.List[string]
$skip = $false
foreach ($l in $lines) {
  if ($l -match '^# >>> lerd ') { $skip = $true; continue }
  if ($l -match '^# <<< lerd ') { $skip = $false; continue }
  if (-not $skip) { $acc.Add($l) }
}
while ($acc.Count -gt 0 -and $acc[$acc.Count-1].Trim() -eq '') { $acc.RemoveAt($acc.Count-1) }
$acc.Add('')
$acc.Add('# >>> lerd (.test) >>>  generated by lerd/sync-windows-hosts.sh')
foreach ($d in $domains) { $acc.Add('127.0.0.1' + $tab + $d) }
$acc.Add('# <<< lerd (.test) <<<')
$text = ($acc -join $nl) + $nl
[System.IO.File]::WriteAllText($hosts, $text, (New-Object System.Text.UTF8Encoding($false)))
if ($wasReadOnly) { Set-ItemProperty -LiteralPath $hosts -Name IsReadOnly -Value $true }
ipconfig /flushdns | Out-Null
Write-Output ('  backup: ' + $bak)
Write-Output ('  domains written: ' + $domains.Count)
PS1

# Isi placeholder: satu baris `'domain'` per domain, tanpa trailing comma
# (PowerShell 5.1 menolak trailing comma di array literal).
awk '{ printf "  '\''%s'\''\n", $0 }' <<< "$DOMAINS" > "$PS1.domains"
awk '
  /^LERD_DOMAINS$/ && !done {
    while ((getline line < ARGV[1]) > 0) print line
    close(ARGV[1]); done=1; next
  }
  { print }
' "$PS1.domains" "$PS1" > "$PS1.final"
mv "$PS1.final" "$PS1"
rm -f "$PS1.domains"

grep -q "^  '.*\.test'$\|^  '.*\.localhost'$" "$PS1" \
  || { err "substitusi domain gagal — .ps1 tidak valid, batal"; rm -f "$PS1"; exit 1; }

log "menulis $HOSTS_WIN (satu prompt admin di Windows)…"
if ! OUT="$(powershell.exe -NoProfile -Command "Start-Process powershell -Verb RunAs -Wait -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File','$PS1_WIN'" 2>&1 | tr -d '\r')"; then
  rm -f "$PS1"
  err "elevasi ditolak atau PowerShell gagal:"
  printf '%s\n' "$OUT" | sed 's/^/    /' >&2
  exit 1
fi
rm -f "$PS1"

case "$OUT" in
  *"canceled by the user"*|*"operation has been canceled"*|*"was canceled"*)
    err "prompt UAC ditolak — hosts tidak ditulis"; exit 1;;
esac

# --- 5. verifikasi ---------------------------------------------------------
if in_sync; then
  log "selesai. hosts Windows sinkron ($COUNT domain)"
else
  err "verifikasi gagal: blok di hosts tidak cocok — cek $HOSTS_WIN dan backup di sebelahnya"
  exit 1
fi
